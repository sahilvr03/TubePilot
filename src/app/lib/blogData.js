// Helper: get post by slug
export function getPostBySlug(slug) {
  return BLOG_POSTS.find(p => p.slug === slug) || null;
}

// Helper: get related posts
export function getRelatedPosts(slug) {
  const post = getPostBySlug(slug);
  if (!post) return [];
  return (post.relatedSlugs || [])
    .map(s => getPostBySlug(s))
    .filter(Boolean)
    .slice(0, 3);
}

// Helper: get posts by category
export function getPostsByCategory(categorySlug) {
  return BLOG_POSTS.filter(p => p.categorySlug === categorySlug);
}

// Helper: get featured posts
export function getFeaturedPosts() {
  return BLOG_POSTS.filter(p => p.featured);
}

// Helper: generate static params for Next.js
export function getAllSlugs() {
  return BLOG_POSTS.map(p => ({ slug: p.slug }));
}

// Helper: get all categories (deduplicated)
export function getAllCategories() {
  const seen = new Set();
  return BLOG_POSTS
    .map(p => ({ name: p.category, slug: p.categorySlug }))
    .filter(c => {
      if (seen.has(c.slug)) return false;
      seen.add(c.slug);
      return true;
    });
}